import {test,expect} from "@playwright/test";

test("blank Workshop creation, battle result, checkpoint and portable import",async({page},testInfo)=>{
 test.setTimeout(60000);
 const errors=[];
 page.on("pageerror",e=>errors.push(e.message));
 await page.goto("/index.html");
 await page.getByRole("link",{name:"New module"}).click();
 await page.getByLabel("Module name").fill("Orchard Siege");
 await page.getByLabel("Starting layout").selectOption("blank");
 await page.getByRole("button",{name:"Open Workshop"}).click();
 const workshop=page.url();
 await page.getByRole("button",{name:"Validate",exact:true}).click();
 await expect(page.getByRole("status")).toContainText("Deck size");
 await page.getByRole("button",{name:"Cards",exact:true}).click();
 await page.getByRole("button",{name:"Add unit"}).click();
 await page.getByLabel("Card name").fill("Orchard Warden");
 await page.getByLabel("Attack", {exact:true}).fill("9");
 await page.getByLabel("Health", {exact:true}).fill("4");
 await page.getByRole("button",{name:"Decks",exact:true}).click();
 await page.getByLabel("Copies of Orchard Warden").fill("4");
 await page.getByLabel("Deck",{exact:true}).selectOption("1");
 await page.getByLabel("Copies of Orchard Warden").fill("4");
 await page.getByRole("button",{name:"Rules",exact:true}).click();
 await page.getByLabel("Starting life").fill("8");
 await page.getByRole("button",{name:"Undo",exact:true}).click();
 await expect(page.getByLabel("Starting life")).toHaveValue("12");
 await page.getByRole("button",{name:"Redo",exact:true}).click();
 await expect(page.getByLabel("Starting life")).toHaveValue("8");
 await page.getByRole("button",{name:"Save checkpoint"}).click();
 await page.reload();
 await page.getByRole("button",{name:"Cards",exact:true}).click();
 await expect(page.getByLabel("Card name")).toHaveValue("Orchard Warden");
 await page.getByRole("button",{name:"Playtest",exact:true}).click();
 await page.getByLabel("Animation speed").selectOption("reduced");
 await page.getByRole("button",{name:"Start match"}).click();
 await page.getByRole("button",{name:"Keep hand"}).click();
 await expect(page.getByRole("button",{name:"End turn",exact:true})).toBeVisible();
 const hand=page.locator(".hand:not(.opponent)");
 await hand.getByRole("button",{name:"Orchard Warden"}).first().click();
 await page.getByRole("button",{name:"Deploy unit · 1 energy"}).click();
 await expect(page.locator(".friendly .card")).toHaveCount(1);
 await page.getByRole("button",{name:"Declare attacks"}).click();
 await page.getByRole("combobox",{name:"Orchard Warden",exact:true}).selectOption({label:"Opponent"});
 await page.getByRole("button",{name:"Confirm",exact:true}).click();
 await expect(page.locator(".result")).toHaveText("Victory");
 await expect(page.getByRole("status")).toContainText("Life reached 0");
 await page.screenshot({path:testInfo.outputPath("battle-result.png")});
 await page.getByRole("button",{name:"Return to Workshop"}).click();
 await expect(page.getByLabel("Card name")).toHaveValue("Orchard Warden");
 const downloadPromise=page.waitForEvent("download");
 await page.getByRole("button",{name:"Export draft ZIP"}).click();
 const download=await downloadPromise;
 await page.goto("/index.html");
 await page.getByLabel("Portable module ZIP").setInputFiles({name:"broken.zip",mimeType:"application/zip",buffer:Buffer.from("invalid")});
 await expect(page.getByRole("status")).toContainText("Import failed");
 await page.getByLabel("Portable module ZIP").setInputFiles(await download.path());
 await expect(page.getByRole("heading",{name:"Orchard Siege",exact:true})).toBeVisible();
 await page.getByRole("link",{name:"Workshop",exact:true}).click();
 await page.getByRole("button",{name:"Cards",exact:true}).click();
 await expect(page.getByLabel("Card name")).toHaveValue("Orchard Warden");
 expect(page.url()).not.toBe(workshop);
 expect(errors).toEqual([]);
});

test("lane board edits survive playtest and apply to the tabletop",async({page},info)=>{
 test.setTimeout(60000);
 await page.goto("/index.html");
 await page.getByRole("link",{name:"New module"}).click();
 await page.getByLabel("Module name").fill("Harbor Lines");
 await page.getByLabel("Starting layout").selectOption("lanes");
 await page.getByRole("button",{name:"Open Workshop"}).click();
 await page.getByRole("button",{name:"Board",exact:true}).click();
 await page.getByLabel("Your west lane name").fill("Breakwater");
 await page.getByLabel("Your east lane capacity").fill("2");
 await page.getByRole("button",{name:"Move Breakwater later on your side"}).click();
 await expect(page.locator(".board-row").last().locator(".board-slot strong").last()).toHaveText("Breakwater");
 await page.getByLabel("Table perspective").selectOption("b");
 await expect(page.locator(".board-row").first().locator(".board-slot strong").last()).toHaveText("Breakwater");
 await page.getByRole("button",{name:"Rules",exact:true}).click();
 await page.getByLabel("Victory condition").selectOption("deck");
 await expect(page.getByText("Players lose when they cannot draw a required card.",{exact:false})).toBeVisible();
 await page.getByRole("button",{name:"Playtest",exact:true}).click();
 await page.getByLabel("Animation speed").selectOption("reduced");
 await page.getByRole("button",{name:"Start match"}).click();
 await expect(page.locator(".friendly .zone h2").last()).toHaveText("Breakwater");
 await expect(page.getByRole("button",{name:"Keep hand"})).toBeVisible();
 await page.screenshot({path:info.outputPath("lane-table.png")});
 await page.getByRole("button",{name:"Workshop",exact:true}).click();
 await expect(page.getByLabel("Victory condition")).toHaveValue("deck");
});
