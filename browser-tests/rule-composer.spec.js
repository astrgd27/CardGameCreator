import {test,expect} from "@playwright/test";

test("composed card ability resolves on the board and stays editable after ZIP import",async({page})=>{
 test.setTimeout(60000);
 await page.goto("/index.html");
 await page.getByRole("link",{name:"New module"}).click();
 await page.getByLabel("Module name").fill("Signal Grove");
 await page.getByRole("button",{name:"Open Workshop"}).click();
 await page.getByRole("button",{name:"Rule composer",exact:true}).click();
 await page.getByRole("button",{name:"Add ability"}).click();
 await page.getByLabel("Ability name").fill("Signal the grove");
 await page.getByLabel("Source card").selectOption({label:"Mosswing Scout"});
 await page.getByLabel("Cost resource").selectOption("energy");
 await page.getByLabel("Cost amount").fill("1");
 await page.getByLabel("Eligible cards").selectOption("self");
 await page.getByRole("button",{name:"Add step"}).click();
 await page.locator(".rule-step").last().getByLabel("Effect").selectOption("draw");
 await expect(page.getByText("Draw 1 card.",{exact:true})).toBeVisible();
 await page.getByRole("button",{name:"Validate",exact:true}).click();
 await expect(page.getByRole("status")).toHaveText("Draft is ready to play.");
 await page.getByRole("button",{name:"Playtest",exact:true}).click();
 await page.getByLabel("Animation speed").selectOption("reduced");
 await page.getByRole("button",{name:"Start match"}).click();
 await page.getByRole("button",{name:"Keep hand"}).click();
 await expect(page.getByRole("button",{name:"End turn",exact:true})).toBeVisible();
 const hand=page.locator(".hand:not(.opponent)");
 await hand.getByRole("button",{name:"Mosswing Scout"}).first().click();
 await page.getByRole("button",{name:"Deploy unit · 1 energy"}).click();
 const card=page.locator(".friendly").getByRole("button",{name:"Mosswing Scout",exact:true});
 await card.click();
 await page.getByRole("button",{name:"Signal the grove · 1 energy"}).click();
 await expect(page.getByRole("status")).toContainText("Choose card");
 await card.click();
 await expect(card).toHaveClass(/resting/);
 await expect(hand.getByRole("button")).toHaveCount(3);
 await expect(page.locator(".seat").last()).toContainText("Energy 1");
 await card.click();
 await expect(page.getByRole("button",{name:"Signal the grove · 1 energy"})).toHaveCount(0);
 await page.getByRole("button",{name:"Workshop",exact:true}).click();
 await expect(page.getByLabel("Ability name")).toHaveValue("Signal the grove");
 const downloadPromise=page.waitForEvent("download");
 await page.getByRole("button",{name:"Export draft ZIP"}).click();
 const download=await downloadPromise;
 await page.goto("/index.html");
 await page.getByLabel("Portable module ZIP").setInputFiles(await download.path());
 await page.getByRole("link",{name:"Workshop",exact:true}).click();
 await page.getByRole("button",{name:"Rule composer",exact:true}).click();
 await expect(page.getByLabel("Ability name")).toHaveValue("Signal the grove");
 await expect(page.getByText("Draw 1 card.",{exact:true})).toBeVisible();
});
